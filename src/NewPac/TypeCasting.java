package NewPac;

public class TypeCasting {

	public static void main(String[] args) {
		
		int val = 100;
		
		long lvalue = val;
		
		System.out.println(lvalue);
		
		float f = 10.5f;
		double dvalue = f;
		
		System.out.println(dvalue);
		
		
		long v = 1800;
		
		int  s  = (int)v;
		
		System.out.println(s);
		
		
		
		
		

		
	}

}
